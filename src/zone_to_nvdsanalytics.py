#!/usr/bin/env python3
"""Render the normalized zones in settings.yaml as a DeepStream nvdsanalytics
ROI config, so the restricted zone can be drawn by the pipeline's OSD.

Only useful if your PipeGen-generated pipeline exposes (or lets you add) an
nvdsanalytics element. Keys follow NVIDIA's sample config_nvdsanalytics.txt;
check them against the DeepStream version on the target machine.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Optional

from config_loader import DEFAULT_CONFIG_PATH, PROJECT_ROOT, ConfigError, load_config
from zone_manager import ZoneError, zones_from_config


def render(zones, width: int, height: int, stream_id: int = 0) -> str:
    lines = [
        "# Generated by zone_to_nvdsanalytics.py from config/settings.yaml",
        "[property]",
        "enable=1",
        f"config-width={width}",
        f"config-height={height}",
        "osd-mode=2",
        "display-font-size=12",
        "",
        f"[roi-filtering-stream-{stream_id}]",
        "enable=1",
    ]
    for z in zones:
        x1, y1, x2, y2 = z.to_pixels(width, height)
        lines.append(f"roi-{z.id}={x1};{y1};{x2};{y1};{x2};{y2};{x1};{y2}")
    lines += ["inverse-roi=0", "class-id=-1", ""]
    return "\n".join(lines)


def main(argv: Optional[list[str]] = None) -> int:
    ap = argparse.ArgumentParser(description="Render settings.yaml zones as an nvdsanalytics ROI config")
    ap.add_argument("--config", default=str(DEFAULT_CONFIG_PATH))
    ap.add_argument("--width", type=int, help="defaults to input.frame_width (use the streammux width)")
    ap.add_argument("--height", type=int, help="defaults to input.frame_height (use the streammux height)")
    ap.add_argument("--out", default=str(PROJECT_ROOT / "config" / "config_nvdsanalytics.txt"))
    args = ap.parse_args(argv)
    try:
        cfg = load_config(args.config)
        zones = zones_from_config(cfg["zones"])
    except (ConfigError, ZoneError) as exc:
        print(f"configuration error: {exc}", file=sys.stderr)
        return 2
    w = args.width or int(cfg["input"]["frame_width"])
    h = args.height or int(cfg["input"]["frame_height"])
    if w <= 0 or h <= 0:
        print(f"width/height must be positive, got {w}x{h}", file=sys.stderr)
        return 2
    try:
        Path(args.out).write_text(render(zones, w, h))
    except OSError as exc:
        print(f"cannot write {args.out}: {exc}", file=sys.stderr)
        return 1
    print(f"wrote {args.out} ({w}x{h})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
